    public function generateCouponCode(): void
    {
        $prefix = Str::upper(Str::substr(Str::slug($this->couponName, ''), 0, 4));
        if ($prefix === '') {
            $prefix = 'TP';
        }

        $this->couponCode = $prefix.'-'.Str::upper(Str::random(6));
        $this->couponAutoGenerated = true;
    }

    public function saveCoupon(): void
    {
        $this->authorize('storefront.catalog.manage');

        $branchId = $this->resolveBranchId();
        $normalizedCode = $this->normalizeCouponCode($this->couponCode);

        $codeRule = Rule::unique('storefront_coupons', 'code')
            ->where(fn ($query) => $query->where('branch_id', $branchId));

        if ($this->editingCouponId) {
            $codeRule = $codeRule->ignore($this->editingCouponId);
        }

        $validated = $this->validate([
            'couponName' => ['required', 'string', 'max:191'],
            'couponDescription' => ['nullable', 'string', 'max:4000'],
            'couponDiscountType' => ['required', Rule::in(['fixed', 'percent'])],
            'couponDiscountValue' => [
                'required',
                'numeric',
                'min:0',
                function (string $attribute, mixed $value, \Closure $fail): void {
                    if ($this->couponDiscountType === 'percent' && (float) $value > 100) {
                        $fail('Percentage discount cannot exceed 100.');
                    }
                },
            ],
            'couponMinSubtotal' => ['nullable', 'numeric', 'min:0'],
            'couponMaxDiscountAmount' => ['nullable', 'numeric', 'min:0'],
            'couponStartsAt' => ['nullable', 'date'],
            'couponEndsAt' => ['nullable', 'date', 'after_or_equal:couponStartsAt'],
            'couponUsageLimit' => ['nullable', 'integer', 'min:1'],
            'couponPerCustomerLimit' => ['nullable', 'integer', 'min:1'],
            'couponActive' => ['boolean'],
        ]);

        validator(
            ['couponCode' => $normalizedCode],
            ['couponCode' => ['required', 'string', 'max:80', 'regex:/^[A-Z0-9_-]+$/', $codeRule]]
        )->validate();

        $payload = [
            'branch_id' => $branchId,
            'name' => $this->sanitizeText($validated['couponName']) ?? 'Coupon',
            'code' => $normalizedCode,
            'description' => $this->sanitizeText($validated['couponDescription'] ?? null),
            'discount_type' => $validated['couponDiscountType'],
            'discount_value' => round((float) $validated['couponDiscountValue'], 2),
            'min_subtotal' => $validated['couponMinSubtotal'],
            'max_discount_amount' => $validated['couponMaxDiscountAmount'],
            'starts_at' => $validated['couponStartsAt'] ?: null,
            'ends_at' => $validated['couponEndsAt'] ?: null,
            'usage_limit' => $validated['couponUsageLimit'],
            'per_customer_limit' => $validated['couponPerCustomerLimit'],
            'is_active' => (bool) $validated['couponActive'],
            'is_auto_generated' => $this->couponAutoGenerated,
        ];

        if ($this->editingCouponId) {
            StorefrontCoupon::query()->findOrFail($this->editingCouponId)->update($payload);
            session()->flash('success', 'Coupon updated.');
        } else {
            $payload['used_count'] = 0;
            StorefrontCoupon::query()->create($payload);
            session()->flash('success', 'Coupon created.');
        }

        $this->resetCouponForm();
        $this->showCouponModal = false;
    }

