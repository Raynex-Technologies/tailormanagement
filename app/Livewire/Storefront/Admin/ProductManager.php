        $this->resetCouponForm();
        $this->showCouponModal = true;
    }

    public function closeCouponModal(): void
    {
        $this->showCouponModal = false;
        $this->resetCouponForm();
    }

    protected function syncProductVariants(InventoryItem $product, array $sizes, array $colors): void
    {
        $variants = [];
        $index = 1;

        if ($sizes !== [] && $colors !== []) {
            foreach ($sizes as $size) {
                foreach ($colors as $color) {
                    $variants[] = $this->variantPayload($product, $size, $color, $index++);
                }
            }
        } elseif ($sizes !== []) {
            foreach ($sizes as $size) {
                $variants[] = $this->variantPayload($product, $size, null, $index++);
            }
        } elseif ($colors !== []) {
            foreach ($colors as $color) {
                $variants[] = $this->variantPayload($product, null, $color, $index++);
            }
        }

        $product->variants()->delete();

        if ($variants !== []) {
            $product->variants()->createMany($variants);
        }
    }

    protected function variantPayload(InventoryItem $product, ?string $size, ?string $color, int $index): array
    {
        $sizeLabel = $size ? strtoupper($size) : null;
        $colorLabel = $this->normalizeColorValue($color);

        $name = trim(implode(' / ', array_filter([$sizeLabel, $colorLabel])));
        if ($name === '') {
            $name = 'Variant '.$index;
        }

        return [
            'name' => $name,
            'size' => $sizeLabel,
            'color' => $colorLabel,
            'sku' => $product->sku.'-V'.str_pad((string) $index, 2, '0', STR_PAD_LEFT),
            'price_delta' => 0,
            'stock_qty' => null,
            'option_values' => [
                'size' => $sizeLabel,
                'color' => $colorLabel,
            ],
            'is_active' => true,
        ];
    }

    protected function normalizeColorValue(?string $value): ?string
    {
        $candidate = trim(strip_tags((string) $value));
        if ($candidate === '') {
            return null;
        }

        if (preg_match('/^#([0-9a-fA-F]{3})$/', $candidate, $matches)) {
            $hex = strtoupper($matches[1]);

            return '#'.$hex[0].$hex[0].$hex[1].$hex[1].$hex[2].$hex[2];
        }

        if (preg_match('/^#([0-9a-fA-F]{6})$/', $candidate)) {
            return '#'.strtoupper(substr($candidate, 1));
        }

        return Str::title(Str::lower($candidate));
    }

    protected function appendGalleryUploads(InventoryItem $product): void
    {
        $uploads = array_filter($this->productGalleryUploads);
        if ($uploads === []) {
            $this->syncGalleryImagesColumn($product->fresh('media'));

            return;
        }

        $maxSort = (int) ($product->media()->max('sort_order') ?? 0);
        foreach ($uploads as $upload) {
            $path = StorefrontMedia::store($upload, 'storefront/products/gallery');
            $maxSort++;

            $product->media()->create([
                'path' => $path,
                'alt_text' => $product->name,
                'sort_order' => $maxSort,
            ]);
        }

        $this->syncGalleryImagesColumn($product->fresh('media'));
        $this->productGalleryUploads = [];
    }

    protected function syncGalleryImagesColumn(InventoryItem $product): void
    {
        $paths = $product->media->pluck('path')->values()->all();
        $product->update([
            'gallery_images' => $paths,
        ]);
    }

    protected function resolveBranchId(): int
    {
        $user = auth()->user();
        if (! $user) {
            throw ValidationException::withMessages([
                'tab' => 'Authenticated user is required.',
            ]);
        }

        if (! $user->isGlobalAdmin()) {
            if (! $user->branch_id) {
                throw ValidationException::withMessages([
                    'tab' => 'Your account is not assigned to a branch.',
                ]);
            }

            return (int) $user->branch_id;
        }

        $branchId = BranchContext::id() ?: $user->branch_id;
        if (! $branchId) {
            throw ValidationException::withMessages([
                'tab' => 'Select a branch from the branch switcher before creating storefront records.',
            ]);
        }

        return (int) $branchId;
    }

    protected function generateUniqueProductSlug(string $name, int $branchId, ?int $ignoreId = null): string
    {
        $baseSlug = Str::slug($name);
        if ($baseSlug === '') {
            $baseSlug = 'product';
        }

        $candidate = $baseSlug;
        $suffix = 2;

        while (InventoryItem::query()
            ->withoutBranchScope()
            ->where('branch_id', $branchId)
            ->where('slug', $candidate)
            ->when($ignoreId !== null, fn ($query) => $query->where('id', '!=', $ignoreId))
            ->exists()) {
            $candidate = $baseSlug.'-'.$suffix;
            $suffix++;
        }

        return $candidate;
    }

    protected function generateUniqueComboSlug(string $name, int $branchId, ?int $ignoreId = null): string
    {
        $baseSlug = Str::slug($name);
        if ($baseSlug === '') {
            $baseSlug = 'combo';
        }

        $candidate = $baseSlug;
        $suffix = 2;

        while (StorefrontProductCombo::query()
            ->withoutBranchScope()
            ->where('branch_id', $branchId)
            ->where('slug', $candidate)
            ->when($ignoreId !== null, fn ($query) => $query->where('id', '!=', $ignoreId))
            ->exists()) {
            $candidate = $baseSlug.'-'.$suffix;
            $suffix++;
        }

        return $candidate;
    }

    protected function prepareSku(?string $provided): string
    {
        $candidate = strtoupper(trim((string) $provided));
        if ($candidate !== '') {
            return $candidate;
        }

        do {
            $candidate = 'PRD-'.Str::upper(Str::random(8));
        } while (InventoryItem::query()->withoutBranchScope()->where('sku', $candidate)->exists());

        return $candidate;
    }

    protected function dimensionsPayload(?float $length, ?float $width, ?float $height): ?array
    {
        $payload = array_filter([
            'length' => $length,
            'width' => $width,
            'height' => $height,
        ], fn ($value) => $value !== null && $value !== '');

        return $payload === [] ? null : $payload;
    }

    /**
     * @return array<int, string>
     */
    protected function splitCsv(string $value): array
    {
        return collect(explode(',', $value))
            ->map(fn ($item) => trim(strip_tags($item)))
            ->filter()
            ->unique()
            ->values()
            ->all();
    }

    protected function sanitizeText(?string $value): ?string
    {
        if ($value === null) {
            return null;
        }

        $sanitized = trim(strip_tags($value));

        return $sanitized === '' ? null : $sanitized;
    }

    protected function normalizeCouponCode(string $code): string
    {
        $normalized = strtoupper(trim(strip_tags($code)));
        $normalized = preg_replace('/\s+/', '', $normalized) ?: '';

        return $normalized;
    }

    public function render()
    {
        $products = InventoryItem::query()
            ->with(['category', 'stock', 'media'])
            ->when($this->productSearch !== '', function ($query) {
                $query->where(function ($inner) {
                    $term = '%'.$this->productSearch.'%';
                    $inner->where('name', 'like', $term)
                        ->orWhere('sku', 'like', $term)
                        ->orWhere('slug', 'like', $term);
                });
            })
            ->orderByDesc('id')
            ->paginate($this->perPage, ['*'], 'productsPage');

        $combos = StorefrontProductCombo::query()
            ->withCount('items')
            ->when($this->comboSearch !== '', function ($query) {
                $term = '%'.$this->comboSearch.'%';
                $query->where(function ($inner) use ($term) {
                    $inner->where('name', 'like', $term)
                        ->orWhere('slug', 'like', $term);
                });
            })
            ->orderBy('sort_order')
            ->orderByDesc('id')
            ->paginate($this->perPage, ['*'], 'combosPage');

        $coupons = StorefrontCoupon::query()
            ->when($this->couponSearch !== '', function ($query) {
                $term = '%'.strtoupper($this->couponSearch).'%';
                $query->where(function ($inner) use ($term) {
                    $inner->whereRaw('UPPER(name) like ?', [$term])
                        ->orWhereRaw('UPPER(code) like ?', [$term]);
                });
            })
            ->orderByDesc('id')
            ->paginate($this->perPage, ['*'], 'couponsPage');

        return view('livewire.storefront.admin.product-manager', [
            'products' => $products,
            'combos' => $combos,
            'coupons' => $coupons,
            'categories' => InventoryCategory::query()->orderBy('name')->get(['id', 'name']),
            'productOptions' => InventoryItem::query()
                ->where('status', 'active')
                ->where('is_active', true)
                ->orderBy('name')
                ->get(['id', 'name', 'sku']),
        ]);
    }
