    public function deleteCoupon(int $couponId): void
    {
        $this->authorize('storefront.catalog.manage');

        $coupon = StorefrontCoupon::query()->findOrFail($couponId);
        $hasUsages = StorefrontCouponUsage::query()->where('storefront_coupon_id', $coupon->id)->exists();

        if ($hasUsages) {
            $coupon->update(['is_active' => false]);
            session()->flash('success', 'Coupon has existing usage records and was disabled instead of deleted.');

            return;
        }

        $coupon->delete();

        if ($this->editingCouponId === $couponId) {
            $this->resetCouponForm();
        }

        session()->flash('success', 'Coupon deleted.');
    }

