    public function saveCombo(): void
    {
        $this->authorize('storefront.catalog.manage');

        $validated = $this->validate([
            'comboName' => ['required', 'string', 'max:191'],
            'comboDescription' => ['nullable', 'string', 'max:4000'],
            'comboPrice' => ['required', 'numeric', 'min:0'],
            'comboProductIds' => ['required', 'array', 'min:1'],
            'comboProductIds.*' => ['integer', 'exists:inventory_items,id'],
            'comboActive' => ['boolean'],
            'comboVisible' => ['boolean'],
            'comboSortOrder' => ['nullable', 'integer', 'min:0', 'max:9999'],
            'comboFeaturedImageUpload' => [
                'nullable',
                'image',
                'mimes:jpg,jpeg,png,webp',
                'mimetypes:image/jpeg,image/png,image/webp',
                'max:4096',
                'dimensions:min_width=64,min_height=64,max_width=4096,max_height=4096',
            ],
        ]);

        $branchId = $this->resolveBranchId();
        $name = $this->sanitizeText($validated['comboName']) ?? 'Combo';

        $combo = $this->editingComboId
            ? StorefrontProductCombo::query()->findOrFail($this->editingComboId)
            : new StorefrontProductCombo();

        $payload = [
            'branch_id' => $branchId,
            'name' => $name,
            'slug' => $this->generateUniqueComboSlug($name, $branchId, $this->editingComboId),
            'description' => $this->sanitizeText($validated['comboDescription'] ?? null),
            'price' => round((float) $validated['comboPrice'], 2),
            'is_active' => (bool) $validated['comboActive'],
            'storefront_is_visible' => (bool) $validated['comboVisible'],
            'sort_order' => (int) ($validated['comboSortOrder'] ?? 0),
        ];

        if ($this->comboFeaturedImageUpload) {
            if ($combo->exists && $combo->featured_image_path) {
                StorefrontMedia::delete($combo->featured_image_path);
            }

            $payload['featured_image_path'] = StorefrontMedia::store($this->comboFeaturedImageUpload, 'storefront/combos');
        }

        $combo->fill($payload);
        $combo->save();

        $syncPayload = [];
        foreach ($validated['comboProductIds'] as $productId) {
            $syncPayload[(int) $productId] = ['quantity' => 1];
        }
        $combo->products()->sync($syncPayload);

        session()->flash('success', $this->editingComboId ? 'Combo updated.' : 'Combo created.');
        $this->resetComboForm();
        $this->showComboModal = false;
    }

